def parse_json(text):
    """Turn the AI reply into a Python object, tolerating Markdown fences."""
    if not text or not text.strip():
        raise ValueError("the reply was empty")
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
    cleaned = re.sub(r"\s*```$", "", cleaned)
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        start, end = cleaned.find("{"), cleaned.rfind("}")
        if start != -1 and end > start:
            try:
                return json.loads(cleaned[start:end + 1])
            except json.JSONDecodeError:
                pass
    raise ValueError("the reply was not valid JSON")


def _text(value):
    return value.strip() if isinstance(value, str) else ""


def _strip_option_prefix(text):
    return re.sub(r"^\s*\(?[A-Da-d]\)?[\.\):]\s+", "", text).strip()


def normalize_mcq(item):
    """Return a clean MCQ dict or None if the item is unusable."""
    if not isinstance(item, dict):
        return None
    question = _text(item.get("question"))
    explanation = _text(item.get("explanation"))
    raw_options = item.get("options")

    if isinstance(raw_options, dict):
        options = [_strip_option_prefix(_text(raw_options.get(k))) for k in "ABCD"]
    elif isinstance(raw_options, list) and len(raw_options) == 4:
        options = [_strip_option_prefix(_text(o)) for o in raw_options]
    else:
        return None

    if not question or not explanation or not all(options):
        return None
    if len({o.lower() for o in options}) != 4:
        return None

    correct = _text(item.get("correct")).upper()
    letter = None
    if correct[:1] in list("ABCD") and (len(correct) == 1 or not correct[1:2].isalpha()):
        letter = correct[:1]
    else:
        for index, option in enumerate(options):
            if option.lower() == _text(item.get("correct")).lower():
                letter = "ABCD"[index]
    if letter is None:
        return None

    return {
        "question": question,
        "options": options,
        "correct": letter,
        "explanation": explanation,
    }


def normalize_qa(item):
    if not isinstance(item, dict):
        return None
    question = _text(item.get("question"))
    answer = _text(item.get("answer"))
    if not question or not answer:
        return None
    return {"question": question, "answer": answer}


def _fingerprint(question):
    return re.sub(r"\W+", "", question.lower())


def validate_section(kind, data):
    """Check the AI reply and return exactly the required number of items."""
    spec = SECTIONS[kind]
    items = data.get(spec["key"]) if isinstance(data, dict) else None
    if not isinstance(items, list):
        raise ValueError(f'the JSON did not contain a "{spec["key"]}" list')

    normalizer = normalize_mcq if kind == "mcq" else normalize_qa
    good, seen = [], set()
    for raw in items:
        item = normalizer(raw)
        if item is None:
            continue
        fingerprint = _fingerprint(item["question"])
        if fingerprint in seen:
            continue
        seen.add(fingerprint)
        good.append(item)

    if len(good) < spec["count"]:
        raise ValueError(
            f"only {len(good)} valid, non-duplicate items were returned but "
            f"exactly {spec['count']} are required"
        )
    return good[: spec["count"]]


