MCQ_SCHEMA = (
    '{"mcqs": [{"question": "...", "options": {"A": "...", "B": "...", '
    '"C": "...", "D": "..."}, "correct": "A", "explanation": "..."}]}'
)
SHORT_SCHEMA = '{"short_questions": [{"question": "...", "answer": "..."}]}'
LONG_SCHEMA = '{"long_questions": [{"question": "...", "answer": "..."}]}'

SECTIONS = {
    "mcq": {
        "count": NUM_MCQ,
        "key": "mcqs",
        "schema": MCQ_SCHEMA,
        "label": "multiple-choice questions (MCQs)",
        "rules": (
            "- Each MCQ has one clear question, exactly four options (A, B, C, D) "
            "and exactly ONE correct option.\n"
            "- Wrong options must be believable but clearly wrong according to the chapter.\n"
            "- Spread the correct answers across A, B, C and D; do not favour one letter.\n"
            "- Do not write options such as 'All of the above' or 'None of the above'.\n"
            '- "correct" must be only one letter: A, B, C or D.\n'
            '- "explanation" is one or two short sentences explaining why the '
            "correct option is right, using the chapter.\n"
            "- Do not put the letters A), B) etc. inside the option text."
        ),
        "tokens": 12000,
    },
    "short": {
        "count": NUM_SHORT,
        "key": "short_questions",
        "schema": SHORT_SCHEMA,
        "label": "short-answer questions",
        "rules": (
            "- Each question can be answered in 2 to 4 sentences.\n"
            '- "answer" is a simple, clear model answer based only on the chapter.'
        ),
        "tokens": 8000,
    },
    "long": {
        "count": NUM_LONG,
        "key": "long_questions",
        "schema": LONG_SCHEMA,
        "label": "long-answer questions",
        "rules": (
            "- Each question needs a detailed answer covering a major topic of the chapter.\n"
            '- "answer" is a complete model answer of about 250 to 450 words, '
            "written in Markdown with short headings (### Heading), bullet "
            "points for important points, and a brief conclusion.\n"
            "- Use only information found in the chapter."
        ),
        "tokens": 16000,
    },
}


def build_prompt(kind, chapter, difficulty, language, avoid, feedback):
    spec = SECTIONS[kind]
    if language == "Urdu":
        language_rule = (
            "Write all question text, options, explanations and answers in "
            "clear, correct Urdu (اردو) script. Keep the JSON keys and the "
            "option letters A, B, C, D in English. If the chapter is in "
            "English, express its ideas faithfully in Urdu."
        )
    else:
        language_rule = "Write everything in clear, simple English."

    avoid_text = ""
    if avoid:
        listed = "\n".join(f"- {q}" for q in avoid[:40])
        avoid_text = (
            "\nQuestions that already exist. Do NOT repeat or rephrase them, "
            f"and choose different topics where possible:\n{listed}\n"
        )

    feedback_text = ""
    if feedback:
        feedback_text = (
            f"\nYour previous reply was rejected because: {feedback}\n"
            "Fix this problem in the new reply.\n"
        )

    return (
        f"Create exactly {spec['count']} {spec['label']} from the chapter below.\n\n"
        "General rules:\n"
        "- Use ONLY the information in the chapter. No outside knowledge.\n"
        "- Questions must be relevant, educationally meaningful and different "
        "from each other. Do not repeat any question.\n"
        f"- {LEVEL_GUIDE[difficulty]}\n"
        f"- {language_rule}\n"
        f"{spec['rules']}\n\n"
        "Reply with a single JSON object in exactly this shape and nothing "
        f"else (no Markdown fences):\n{spec['schema']}\n"
        f"{avoid_text}{feedback_text}\n"
        "<chapter>\n"
        f"{chapter}\n"
        "</chapter>"
    )


# --------------------------------------------------------------------------
# Parsing and validation of the AI reply
# --------------------------------------------------------------------------
def parse_json(text):
    """Turn the AI reply into a Python object, tolerating Markdown fences."""
    if not text or not text.strip():
        raise ValueError("the reply was empty")
    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
    cleaned = re.sub(r"\s*```$", "", cleaned)
    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        start, end = cleaned.find("{"), cleaned.rfind("}")
        if start != -1 and end > start:
            try:
                return json.loads(cleaned[start:end + 1])
            except json.JSONDecodeError:
                pass
    raise ValueError("the reply was not valid JSON")


def _text(value):
    return value.strip() if isinstance(value, str) else ""


def _strip_option_prefix(text):
    return re.sub(r"^\s*\(?[A-Da-d]\)?[\.\):]\s+", "", text).strip()


def normalize_mcq(item):
    """Return a clean MCQ dict or None if the item is unusable."""
    if not isinstance(item, dict):
        return None
    question = _text(item.get("question"))
    explanation = _text(item.get("explanation"))
    raw_options = item.get("options")

    if isinstance(raw_options, dict):
        options = [_strip_option_prefix(_text(raw_options.get(k))) for k in "ABCD"]
    elif isinstance(raw_options, list) and len(raw_options) == 4:
        options = [_strip_option_prefix(_text(o)) for o in raw_options]
    else:
        return None

    if not question or not explanation or not all(options):
        return None
    if len({o.lower() for o in options}) != 4:
        return None

    correct = _text(item.get("correct")).upper()
    letter = None
    if correct[:1] in list("ABCD") and (len(correct) == 1 or not correct[1:2].isalpha()):
        letter = correct[:1]
    else:
        for index, option in enumerate(options):
            if option.lower() == _text(item.get("correct")).lower():
                letter = "ABCD"[index]
    if letter is None:
        return None

    return {
        "question": question,
        "options": options,
        "correct": letter,
        "explanation": explanation,
    }


def normalize_qa(item):
    if not isinstance(item, dict):
        return None
    question = _text(item.get("question"))
    answer = _text(item.get("answer"))
    if not question or not answer:
        return None
    return {"question": question, "answer": answer}


def _fingerprint(question):
    return re.sub(r"\W+", "", question.lower())


def validate_section(kind, data):
    """Check the AI reply and return exactly the required number of items."""
    spec = SECTIONS[kind]
    items = data.get(spec["key"]) if isinstance(data, dict) else None
    if not isinstance(items, list):
        raise ValueError(f'the JSON did not contain a "{spec["key"]}" list')

    normalizer = normalize_mcq if kind == "mcq" else normalize_qa
    good, seen = [], set()
    for raw in items:
        item = normalizer(raw)
        if item is None:
            continue
        fingerprint = _fingerprint(item["question"])
        if fingerprint in seen:
            continue
        seen.add(fingerprint)
        good.append(item)

    if len(good) < spec["count"]:
        raise ValueError(
            f"only {len(good)} valid, non-duplicate items were returned but "
            f"exactly {spec['count']} are required"
        )
    return good[: spec["count"]]


