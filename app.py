def render_mcqs(mcqs, show_all):
    for number, mcq in enumerate(mcqs, 1):
        with st.container(border=True):
            st.markdown(f"**Q{number}. {mcq['question']}**")
            for letter, option in zip("ABCD", mcq["options"]):
                st.markdown(f"**{letter}.** {option}")
            with st.expander("Show / Hide Answer", expanded=show_all):
                answer = mcq["options"]["ABCD".index(mcq["correct"])]
                st.success(f"Correct answer: {mcq['correct']}. {answer}")
