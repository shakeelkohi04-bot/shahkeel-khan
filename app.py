class ChapterError(Exception):
    """Raised when the uploaded file cannot be used."""


class GenerationError(Exception):
    """Raised when question generation fails (message is user-friendly)."""


# --------------------------------------------------------------------------
# File reading
# --------------------------------------------------------------------------
def clean_text(text: str) -> str:
    """Remove null characters and collapse extra whitespace."""
    text = text.replace("\x00", " ").replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t\u00a0]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def read_pdf(data: bytes) -> str:
    try:
        reader = PdfReader(io.BytesIO(data))
        if reader.is_encrypted:
            if not reader.decrypt(""):
                raise ChapterError(
                    "This PDF is password-protected. Please remove the "
                    "password and upload it again."
                )
        pages = []
        for page in reader.pages:
            try:
                pages.append(page.extract_text() or "")
            except Exception:
                pages.append("")
        return "\n\n".join(pages)
    except ChapterError:
        raise
    except Exception as exc:
        raise ChapterError(
            "The PDF file could not be read. It may be damaged or "
            f"unsupported. ({type(exc).__name__})"
        )


def read_docx(data: bytes) -> str:
    try:
        document = Document(io.BytesIO(data))
        parts = [p.text for p in document.paragraphs if p.text.strip()]
        for table in document.tables:
            for row in table.rows:
                cells = [c.text.strip() for c in row.cells if c.text.strip()]
                if cells:
                    parts.append(" | ".join(cells))
        return "\n".join(parts)
    except Exception as exc:
        raise ChapterError(
            "The DOCX file could not be read. It may be damaged or not a "
            f"real .docx file. ({type(exc).__name__})"
        )


def read_txt(data: bytes) -> str:
    encodings = ["utf-8-sig", "cp1256", "latin-1"]
    if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
        encodings.insert(0, "utf-16")
    for encoding in encodings:
        try:
            return data.decode(encoding)
        except (UnicodeDecodeError, UnicodeError):
            continue
    raise ChapterError("The TXT file could not be decoded. Save it as UTF-8.")


@st.cache_data(show_spinner=False)
def extract_text(file_name: str, data: bytes) -> str:
    """Extract and clean text from a PDF, DOCX or TXT file."""
    if not data:
        raise ChapterError("The uploaded file is empty.")
    if len(data) > MAX_FILE_MB * 1024 * 1024:
        raise ChapterError(f"The file is larger than {MAX_FILE_MB} MB.")

    extension = os.path.splitext(file_name)[1].lower()
    if extension == ".pdf":
        raw = read_pdf(data)
    elif extension == ".docx":
        raw = read_docx(data)
    elif extension == ".txt":
        raw = read_txt(data)
    else:
        raise ChapterError("Unsupported file type. Use PDF, DOCX or TXT.")

    text = clean_text(raw)
    if not text:
        raise ChapterError(
            "No text could be found in this file. If it is a scanned PDF "
            "(pictures of pages), convert it to text first."
        )
    if len(text) < MIN_CHARS:
        raise ChapterError(
            f"The document has only {len(text)} characters of text. It is "
            "too short to create a full set of questions."
        )
    return text


