def build_download_text(results, chapter_name, difficulty, language):
    line = "=" * 70
    out = [
        line,
        f"{APP_TITLE}",
        f"Chapter    : {chapter_name}",
        f"Difficulty : {difficulty}",
        f"Language   : {language}",
        f"Generated  : {datetime.now():%Y-%m-%d %H:%M}",
        line,
        "",
        f"SECTION A: MULTIPLE CHOICE QUESTIONS ({len(results['mcq'])})",
        line,
    ]
    for number, mcq in enumerate(results["mcq"], 1):
        out.append(f"\nQ{number}. {mcq['question']}")
        for letter, option in zip("ABCD", mcq["options"]):
            out.append(f"   {letter}. {option}")
        out.append(f"   Correct Answer: {mcq['correct']}")
        out.append(f"   Explanation: {mcq['explanation']}")

    out += ["", line, f"SECTION B: SHORT QUESTIONS ({len(results['short'])})", line]
    for number, item in enumerate(results["short"], 1):
        out.append(f"\nQ{number}. {item['question']}")
        out.append(f"Answer: {item['answer']}")

    out += ["", line, f"SECTION C: LONG QUESTIONS ({len(results['long'])})", line]
    for number, item in enumerate(results["long"], 1):
        out.append(f"\nQ{number}. {item['question']}")
        out.append(f"Answer:\n{item['answer']}")

    return "\n".join(out) + "\n"


